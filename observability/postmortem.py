"""Automated SRE Post-Mortem Report Generator (AegisOps Slice 5).

Generates comprehensive, auditable incident post-mortems combining LLM diagnosis,
Prometheus telemetry before/after proofs, and append-only audit ledger timelines.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from pydantic import BaseModel, Field

from audit.ledger import LedgerEntry, get_incident_ledger
from dashboard.operations_data import IncidentRow, fetch_incident_rows


class PostMortem(BaseModel):
    incident_id: str
    title: str
    generated_at: str
    fault_kind: str
    outcome: str
    mttr_seconds: float
    what_broke: str | None = None
    why_it_broke: str | None = None
    what_changed_recently: str | None = None
    blast_radius: str | None = None
    affected_services: list[str] = Field(default_factory=list)
    mitigation_action: str | None = None
    rollback_strategy: str | None = None
    live_verified: bool | None = None
    before_metrics: dict[str, Any] | None = None
    after_metrics: dict[str, Any] | None = None
    timeline: list[LedgerEntry] = Field(default_factory=list)
    markdown_report: str = ""


def generate_postmortem(incident_id: str) -> PostMortem | None:
    """Generate structured and Markdown post-mortem for a given incident."""
    try:
        rows = fetch_incident_rows()
    except Exception:
        rows = []

    matching = next((r for r in rows if r.incident_id == incident_id), None)
    if matching is None:
        return None

    rep = matching.report
    now_iso = datetime.now(timezone.utc).isoformat()
    mttr = round(rep.total_latency_ms / 1000.0, 2)
    ledger = get_incident_ledger()
    timeline = ledger.get_audit_trail(incident_id)

    # Build timeline markdown
    timeline_md = ""
    for entry in timeline:
        timeline_md += f"- **`{entry.created_at[11:19]}Z`** `[{entry.event_type}]` by `{entry.actor}`\n"
    if not timeline_md:
        timeline_md = "- *No ledger events recorded for this incident.*\n"

    services_str = ", ".join(rep.affected_services) if rep.affected_services else "mock_app"
    before_str = str(rep.live_metrics_before or {})
    after_str = str(rep.live_metrics_after or {})

    md = f"""# AegisOps SRE Incident Post-Mortem

**Incident ID:** `{rep.incident_id}`  
**Fault Category:** `{rep.fault_kind.value}`  
**Outcome:** `{rep.outcome.value.upper()}`  
**Mean Time to Recover (MTTR):** `{mttr}s`  
**Generated At:** `{now_iso}`  

---

## 1. Executive Summary
- **What Broke:** {rep.what_broke or 'API Service degradation under anomalous condition.'}
- **Why It Broke:** {rep.why_it_broke or 'System resource saturation or unhandled concurrency.'}
- **What Changed Recently:** {rep.what_changed_recently or 'Spike in external traffic or configuration change.'}
- **Blast Radius:** `{rep.blast_radius.value.upper() if rep.blast_radius else 'LOW'}`
- **Affected Services:** `{services_str}`

---

## 2. Recovery & Closed-Loop Verification
- **Mitigation Action Taken:** `{rep.mitigation_action.value if rep.mitigation_action else 'N/A'}`
- **Automated Rollback Safeguard:** {rep.rollback_strategy or 'Revert to baseline state.'}
- **Live SLO Telemetry Assertion:** `{'PASSED (SLO Restored)' if rep.live_verified else 'DEGRADED'}`
- **Telemetry Before Recovery:** `{before_str}`
- **Telemetry After Recovery:** `{after_str}`

---

## 3. Incident Lifecycle Timeline (Audit Ledger)
{timeline_md}

---

## 4. Preventive Follow-Up & Durable Fix
- **Durable Fix Drafted:** `{'Yes - Unified Diff Filed' if rep.durable_fix else 'None required'}`
- **Target File:** `{rep.durable_fix.target_file if rep.durable_fix else 'N/A'}`
- **Operator Notes:** Auto-generated by AegisOps Closed-Loop Self-Healing Platform.
"""

    return PostMortem(
        incident_id=rep.incident_id,
        title=f"Post-Mortem: {rep.fault_kind.value} on {services_str}",
        generated_at=now_iso,
        fault_kind=rep.fault_kind.value,
        outcome=rep.outcome.value,
        mttr_seconds=mttr,
        what_broke=rep.what_broke,
        why_it_broke=rep.why_it_broke,
        what_changed_recently=rep.what_changed_recently,
        blast_radius=rep.blast_radius.value if rep.blast_radius else "low",
        affected_services=rep.affected_services,
        mitigation_action=rep.mitigation_action.value if rep.mitigation_action else None,
        rollback_strategy=rep.rollback_strategy,
        live_verified=rep.live_verified,
        before_metrics=rep.live_metrics_before,
        after_metrics=rep.live_metrics_after,
        timeline=timeline,
        markdown_report=md,
    )
